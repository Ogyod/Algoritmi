REGION_PATTERNS = {code: re.compile(r'\b(?:' + aliases + r')\b') for code, aliases in REGIONS.items()}
REGION_PATTERNS.update({code: re.compile(rf'\b{stem}(?:ая область|ой области|ую область|ая обл|ой обл)\b')
                        for code, stem in OBLASTS.items()})
ISSUANCE = re.compile(r'\b(?:место выдачи|выдан[оа]? в|адрес (?:школы|образовательной организации))\b')
SCHOOL = re.compile(r'\b(?:школ\w*|гимнази\w*|лице[йяе]|образовательн\w* организаци\w*)\b')
LOCATION = re.compile(r'^(?:город|г)\s+|\b(?:область|области|обл|край|края|республика|республики)\b')


def issuing_region(lines):
    regions = set()
    previous = None
    for line in lines:
        text = normalized(line['text'])
        if 'предыдущий документ' in text:
            break
        if line['confidence'] < OCR_THRESHOLD:
            previous = None
            continue
        if ISSUANCE.search(text) or SCHOOL.search(text) or LOCATION.search(text) or previous:
            for code, pattern in REGION_PATTERNS.items():
                if pattern.search(text):
                    regions.add(code)
        # An address often continues on the line after the issuing school.
        previous = ISSUANCE.search(text) or SCHOOL.search(text)
    return regions
